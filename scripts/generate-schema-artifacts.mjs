import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const root = process.cwd();
const mobileRoot = path.resolve(root, "..", "Mobile");
const check = process.argv.includes("--check");
const schemaPath = path.join(root, "schema", "logbook.schema.json");
const constantsPath = path.join(root, "schema", "constants.json");
const defaultsPath = path.join(root, "schema", "default-logbook.json");
const schema = JSON.parse(await fs.readFile(schemaPath, "utf8"));
const constants = JSON.parse(await fs.readFile(constantsPath, "utf8"));
const defaultLogbook = JSON.parse(await fs.readFile(defaultsPath, "utf8"));

function stable(value) { return JSON.stringify(value, null, 2); }
async function ensureDir(file) { await fs.mkdir(path.dirname(file), { recursive: true }); }
const outputs = new Map();
function emit(file, content) { outputs.set(path.resolve(file), content.endsWith("\n") ? content : content + "\n"); }

function standaloneValidatorCode() {
  const ajv = new Ajv2020({ code: { source: true, esm: true }, allErrors: false, strict: false });
  const validate = ajv.compile(schema);
  let code = standaloneCode(ajv, validate);
  code = code.replace("export const validate =", "export const validateSchema =");
  code = code.replace(/export default (validate\d+);?\s*$/m, "export {$1 as validateSchema};\nexport default $1;");
  return "/* This file is generated by scripts/generate-schema-artifacts.mjs. Do not edit by hand. */\n" + code;
}

function rulesCode() {
  return `/* This file is generated by scripts/generate-schema-artifacts.mjs. Do not edit by hand. */
import { validateSchema } from "./logbook-validator.js";

export const constants = ${stable(constants)};
export const defaultLogbook = ${stable(defaultLogbook)};
export const OBJECT_COLLECTION_KEYS = new Set(["lures","flashers","reels","rods","rodReelCombos","people","locations","spots","expeditions","trips"]);

function fail(path, message) { return { valid: false, error: path + ": " + message }; }
function ok() { return { valid: true, error: null }; }
function object(value) { return value !== null && typeof value === "object" && !Array.isArray(value); }
function finite(value) { return typeof value === "number" && Number.isFinite(value); }
function pointerPath(pointer, missing) {
  const parts = pointer ? pointer.slice(1).split("/").filter(Boolean).map(function (part) { return part.replace(/~1/g, "/").replace(/~0/g, "~"); }) : [];
  const out = [];
  for (const part of parts) {
    if (/^\\d+$/.test(part)) {
      if (out.length) out[out.length - 1] += "[" + part + "]";
      else out.push("$[" + part + "]");
    } else out.push(part);
  }
  if (missing) out.push(missing);
  return out.join(".") || "$";
}
function schemaMessage(item, path) {
  if (item.keyword === "required") return "is required";
  if (item.keyword === "type") {
    const type = item.params && item.params.type;
    if (Array.isArray(type)) {
      if (type.includes("number") && type.includes("null")) return path.endsWith(".maxFeet") ? "must be a nonnegative number or null" : "must be a number or null";
      if (type.includes("object") && type.includes("null")) return "must be an object or null";
    }
    if (type === "array") return "must be a list";
    if (type === "object") return "must be an object";
    if (type === "string") return "must be a string";
    if (type === "boolean") return "must be a boolean";
    if (type === "number") return "must be a number";
    if (type === "integer") return "must be an integer";
  }
  if (item.keyword === "const" && path === "schemaVersion") return "must be version 2";
  if (item.keyword === "enum") {
    if (path.indexOf("settings.units.") === 0) return "has an unsupported unit";
    if (path === "settings.theme") return "must be \\\"light\\\" or \\\"dark\\\"";
    if (path === "settings.timeFormat") return "must be \\\"12\\\" or \\\"24\\\"";
    if (path === "settings.defaultHomeLake") return "has an unsupported lake";
    if (path.endsWith("spotAssignmentMode")) return "must be \\\"automatic\\\" or \\\"manual\\\"";
    return "has an unsupported value";
  }
  if (item.keyword === "propertyNames") {
    if (path === "settings.bathymetryLakeCalibrationsFeet") return "has an unsupported lake";
    if (path === "settings.speciesMapColors") return "must not contain an empty species";
    if (path === "settings.defaultSavedSetupIds") return "must not contain an empty method";
    return "contains an unsupported property name";
  }
  if (item.keyword === "pattern") {
    if (path.indexOf("settings.speciesMapColors.") === 0) return "must be a six-digit hex color";
    if (path.endsWith(".filename")) return "must be a filename";
    return "must be a non-empty string";
  }
  if (item.keyword === "minItems") return "must contain at least one rod";
  if (item.keyword === "minimum" || item.keyword === "maximum") {
    const params = item.schema || {};
    if (params.minimum !== undefined && params.maximum !== undefined) return "must be between " + params.minimum + " and " + params.maximum;
    if (params.minimum === 0) return "must be a nonnegative number or null";
    if (params.minimum !== undefined) return "must be at least " + params.minimum;
    if (params.maximum !== undefined) return "must be at most " + params.maximum;
  }
  return item.message || "is invalid";
}
function schemaResult(document) {
  if (validateSchema(document)) return null;
  const item = (validateSchema.errors || [])[0] || {};
  const path = pointerPath(item.instancePath || "", item.params && item.params.missingProperty);
  return fail(path, schemaMessage(item, path));
}
function walkJson(value, path, depth) {
  if (depth > 30) return fail(path, "nesting is too deep");
  if (value === null || typeof value === "string" || typeof value === "boolean") return null;
  if (typeof value === "number") return Number.isFinite(value) ? null : fail(path, "number must be finite");
  if (Array.isArray(value)) {
    for (let index = 0; index < value.length; index += 1) { const bad = walkJson(value[index], path + "[" + index + "]", depth + 1); if (bad) return bad; }
    return null;
  }
  if (object(value)) {
    for (const key of Object.keys(value)) { const bad = walkJson(value[key], path + "." + key, depth + 1); if (bad) return bad; }
    return null;
  }
  return fail(path, "unsupported value type " + typeof value);
}
function isoDate(value) {
  if (!/^\\d{4}-\\d{2}-\\d{2}$/.test(value)) return false;
  const time = Date.parse(value + "T00:00:00Z");
  return Number.isFinite(time) && new Date(time).toISOString().slice(0, 10) === value;
}
function semantic(document) {
  for (const key of OBJECT_COLLECTION_KEYS) {
    const seen = new Set();
    for (let index = 0; index < (document[key] || []).length; index += 1) {
      const id = document[key][index].id;
      if (id) { if (seen.has(id)) return fail(key + "[" + index + "].id", "duplicate id \\\"" + id + "\\\""); seen.add(id); }
    }
  }
  const settings = document.settings;
  if (settings.speciesMapColors !== undefined) {
    const names = new Set();
    for (const species of Object.keys(settings.speciesMapColors)) { const key = species.trim().toLowerCase(); if (names.has(key)) return fail("settings.speciesMapColors", "must not repeat a species"); names.add(key); }
  }
  if (settings.chopRanges !== undefined) {
    const ids = new Set();
    for (let index = 0; index < settings.chopRanges.length; index += 1) { const id = settings.chopRanges[index].id; if (ids.has(id)) return fail("settings.chopRanges[" + index + "].id", "must be unique"); ids.add(id); }
  }
  if (settings.checklists !== undefined) {
    const ids = new Set(); const names = new Set();
    for (let index = 0; index < settings.checklists.length; index += 1) {
      const item = settings.checklists[index]; const path = "settings.checklists[" + index + "]";
      if (ids.has(item.id)) return fail(path + ".id", "must be unique"); ids.add(item.id);
      const name = item.name.trim().toLowerCase(); if (names.has(name)) return fail(path + ".name", "must be unique ignoring case"); names.add(name);
      const itemIds = new Set();
      for (let itemIndex = 0; itemIndex < item.items.length; itemIndex += 1) { const child = item.items[itemIndex]; if (itemIds.has(child.id)) return fail(path + ".items[" + itemIndex + "].id", "must be unique within its checklist"); itemIds.add(child.id); }
    }
  }
  if (settings.privatePhotoLocations !== undefined) {
    const ids = new Set();
    for (let index = 0; index < settings.privatePhotoLocations.length; index += 1) { const id = settings.privatePhotoLocations[index].id; if (ids.has(id)) return fail("settings.privatePhotoLocations[" + index + "].id", "must be unique"); ids.add(id); }
  }
  const spreadIds = new Set();
  if (settings.trollingSpreads !== undefined) {
    const names = new Set();
    for (let index = 0; index < settings.trollingSpreads.length; index += 1) {
      const item = settings.trollingSpreads[index]; const path = "settings.trollingSpreads[" + index + "]";
      if (spreadIds.has(item.id)) return fail(path + ".id", "must be unique"); spreadIds.add(item.id);
      const name = item.name.trim().toLowerCase(); if (names.has(name)) return fail(path + ".name", "must be unique ignoring case"); names.add(name);
    }
  }
  const defaultSpreadId = settings.defaultTrollingSpreadId || "";
  if (defaultSpreadId && !spreadIds.has(defaultSpreadId)) return fail("settings.defaultTrollingSpreadId", "must reference a saved trolling spread");
  const setupMethods = new Map();
  if (settings.savedSetups !== undefined) {
    const ids = new Set(); const namesByMethod = new Map();
    for (let index = 0; index < settings.savedSetups.length; index += 1) {
      const item = settings.savedSetups[index]; const path = "settings.savedSetups[" + index + "]";
      if (ids.has(item.id)) return fail(path + ".id", "must be unique"); ids.add(item.id);
      const methodKey = item.method.trim().toLowerCase(); const set = namesByMethod.get(methodKey) || new Set(); namesByMethod.set(methodKey, set);
      const name = item.name.trim().toLowerCase(); if (set.has(name)) return fail(path + ".name", "must be unique within the method ignoring case"); set.add(name);
      setupMethods.set(item.id, item.method.trim());
    }
  }
  if (settings.defaultSavedSetupIds !== undefined) for (const method of Object.keys(settings.defaultSavedSetupIds)) { const setupMethod = setupMethods.get(settings.defaultSavedSetupIds[method]); if (!setupMethod || setupMethod.toLowerCase() !== method.trim().toLowerCase()) return fail("settings.defaultSavedSetupIds." + method, "must reference a saved setup for that method"); }
  const spotNames = new Set();
  for (let index = 0; index < document.spots.length; index += 1) { const name = document.spots[index].name.trim().toLowerCase(); if (spotNames.has(name)) return fail("spots[" + index + "].name", "must be unique ignoring case"); spotNames.add(name); }
  for (let index = 0; index < document.expeditions.length; index += 1) { const item = document.expeditions[index]; const path = "expeditions[" + index + "]"; if (!isoDate(item.startDate)) return fail(path + ".startDate", "must be a valid ISO date"); if (!isoDate(item.endDate)) return fail(path + ".endDate", "must be a valid ISO date"); if (item.endDate < item.startDate) return fail(path + ".endDate", "must be on or after startDate"); }
  return ok();
}
export function validateLogbook(document) {
  if (!object(document)) return fail("$", "logbook must be a JSON object");
  let bad = walkJson(document, "$", 0); if (bad) return bad;
  if (!Number.isInteger(document.schemaVersion)) return fail("schemaVersion", "must be an integer");
  if (document.schemaVersion !== 2) return fail("schemaVersion", "must be version 2");
  bad = schemaResult(document); if (bad) return bad;
  return semantic(document);
}
`;
}

const desktopGenerated = path.join(root, "static", "js", "generated");
const mobileGenerated = path.join(mobileRoot, "src", "domain", "generated");
const validatorCode = standaloneValidatorCode();
emit(path.join(desktopGenerated, "logbook-validator.js"), validatorCode);
emit(path.join(desktopGenerated, "logbook-schema-rules.js"), rulesCode());
emit(path.join(desktopGenerated, "package.json"), "{\n  \"type\": \"module\"\n}\n");
emit(path.join(mobileGenerated, "logbook-validator.js"), validatorCode);
emit(path.join(mobileGenerated, "logbook-validator.d.ts"), "import type { Logbook } from \"./logbook-schema\";\nexport declare function validateSchema(value: unknown): value is Logbook;\ndeclare const validate: typeof validateSchema;\nexport default validate;\n");
emit(path.join(mobileGenerated, "constants.json"), stable(constants));
emit(path.join(mobileGenerated, "default-logbook.json"), stable(defaultLogbook));
const ts = await compile(schema, "Logbook", {
  bannerComment: "/* This file is generated by scripts/generate-schema-artifacts.mjs. Do not edit by hand. */",
  additionalProperties: true,
  style: { semi: true, singleQuote: false },
});
emit(path.join(mobileGenerated, "logbook-schema.ts"), ts + "\nexport type Logbook = FishingLogbookV2Document;\n");

const stale = [];
for (const [file, content] of outputs) {
  let current = null;
  try { current = await fs.readFile(file, "utf8"); } catch { current = null; }
  if (current !== content) stale.push(file);
  if (!check) { await ensureDir(file); await fs.writeFile(file, content, "utf8"); }
}
if (check && stale.length) {
  console.error("Generated schema artifacts are stale:\n" + stale.map((file) => path.relative(root, file)).join("\n"));
  process.exit(1);
}
console.log(check ? "Generated schema artifacts are fresh." : "Wrote " + outputs.size + " schema artifacts.");
