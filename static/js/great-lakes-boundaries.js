function pointOnSegment(longitude, latitude, [x1, y1], [x2, y2]) {
  const cross = (longitude - x1) * (y2 - y1) - (latitude - y1) * (x2 - x1);
  if (Math.abs(cross) > 1e-8) return false;
  return longitude >= Math.min(x1, x2) - 1e-8
    && longitude <= Math.max(x1, x2) + 1e-8
    && latitude >= Math.min(y1, y2) - 1e-8
    && latitude <= Math.max(y1, y2) + 1e-8;
}

function pointInPolygon(longitude, latitude, polygon) {
  let inside = false;
  for (let index = 0, previous = polygon.length - 1; index < polygon.length; previous = index, index += 1) {
    const a = polygon[previous];
    const b = polygon[index];
    if (pointOnSegment(longitude, latitude, a, b)) return true;
    if ((a[1] > latitude) !== (b[1] > latitude)
      && longitude < ((b[0] - a[0]) * (latitude - a[1])) / (b[1] - a[1]) + a[0]) inside = !inside;
  }
  return inside;
}

export function isPointInsideGreatLake(coordinates) {
  const latitude = Number(coordinates?.latitude);
  const longitude = Number(coordinates?.longitude);
  if (!Number.isFinite(latitude) || !Number.isFinite(longitude)
    || latitude < -90 || latitude > 90 || longitude < -180 || longitude > 180) return false;
  return GREAT_LAKES.some(polygon => pointInPolygon(longitude, latitude, polygon));
}
